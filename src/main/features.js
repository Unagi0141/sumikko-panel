/**
 * 配布版に載せる機能の切り替え。
 *
 * ログイン情報の保存について。
 *
 * 既定は「積まない」。0 を渡して外すのではなく、1 を渡して初めて載る。
 *
 * 配布ページと README に「ログイン情報は保存しません」と書いて配っている。
 * v0.9.4 から v0.9.13 までの配布物は、この既定が逆（!== '0'）になっており、
 * 書いてあることと中身が食い違っていた。文書のほうを書き換えて辻褄を合わせる
 * 選択もあり得たが、
 *
 *   ・「預からない」は、このアプリを入れてもらう理由そのものである
 *   ・暗号化していても、他人のパスワードを黙って抱えるのは負う必要のない責任
 *   ・作者自身の摩擦は環境変数ひとつで解消でき、失うものが無い
 *
 * ことから、実装のほうを文書に戻した。
 *
 * 自分の環境で使いたいときはこうする。
 *
 *   TLDOCK_CREDENTIALS=1 npm start
 *
 * 1 を渡したときだけ、保存と UI と IPC を積む。渡さなければ credentials.js は
 * 読み込まれず、IPC の口も開かない。機能が存在しない状態になる。
 *
 * 有効にしたときでも、動くのは「空欄に入れるだけ」（autoFill）まで。
 * 送信まで行う autoLogin は別項目で、既定は無効のまま。X はログインの自動化に
 * エラーを返すことが実測で分かっており、こちらからボタンを押しにいかない。
 */

const credentials = process.env.TLDOCK_CREDENTIALS === '1';

module.exports = {
  credentials,
};
