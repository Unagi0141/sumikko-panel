/**
 * 配布版に載せる機能の切り替え。
 *
 * ログイン情報の保存について。
 *
 * このアプリの中にはブラウザのパスワードマネージャがない。無効にしていると、
 * ログイン画面が出るたびに利用者が ID とパスワードを手で打つことになる。
 * 実際それが日々いちばんの摩擦になっていたので、既定で有効にする。
 *
 * ただし有効なのは「空欄に入れるだけ」（autoFill）までで、送信はしない。
 * X はログインの自動化にエラーを返すことが実測で分かっており、こちらから
 * ボタンを押しにいくと余計な摩擦を招く。押すのは利用者の操作に委ねる。
 * 送信まで行う autoLogin は別項目で、既定は無効のまま。
 *
 * 保存先は Windows の DPAPI（safeStorage）で暗号化した手元のファイルだけ。
 * 外には出ない。それでも同梱したくない場合は、環境変数で丸ごと外せる。
 *
 *   TLDOCK_CREDENTIALS=0
 *
 * 0 を渡したときだけ、保存も UI も IPC も積まない。
 */

const credentials = process.env.TLDOCK_CREDENTIALS !== '0';

module.exports = {
  credentials,
};
